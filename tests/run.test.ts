import { access, mkdir, mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it, vi, type MockInstance } from "vitest";
import { buildConfig } from "../src/config.js";
import { run } from "../src/run.js";

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function makeTemplateDir(): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), "agents-md-tpl-"));
  await mkdir(join(root, "profiles", "angular"), { recursive: true });
  await writeFile(
    join(root, "profiles", "angular", "AGENTS.md.tmpl"),
    "<!-- include: PROJECT.md -->\n\n<!-- include: CODING.md -->\n",
    "utf8",
  );
  await writeFile(join(root, "profiles", "angular", "CODING.md"), "## Coding (angular)", "utf8");
  return root;
}

async function makeRepo(withProject = true): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "agents-md-repo-"));
  if (withProject) {
    await mkdir(join(dir, ".agents"));
    await writeFile(join(dir, ".agents", "PROJECT.md"), "## Project\n\nBilling UI.\n", "utf8");
  }
  return dir;
}

describe("buildConfig", () => {
  it("resolves paths against baseDir and defaults repo to '.'", () => {
    const cfg = buildConfig({ templateDir: "tpl", profile: "angular", baseDir: "/base" });
    expect(cfg.repoDir).toBe("/base");
    expect(cfg.templateDir).toBe("/base/tpl");
    expect(cfg.skip).toEqual([]);
  });

  it("keeps absolute paths", () => {
    const cfg = buildConfig({
      repo: "/r",
      templateDir: "/t",
      profile: "p",
      skip: ["BUILD"],
      baseDir: "/base",
    });
    expect(cfg.repoDir).toBe("/r");
    expect(cfg.templateDir).toBe("/t");
    expect(cfg.skip).toEqual(["BUILD"]);
  });
});

describe("run", () => {
  let logSpy: MockInstance<(...args: unknown[]) => void>;
  let errSpy: MockInstance<(...args: unknown[]) => void>;

  beforeEach(() => {
    logSpy = vi.spyOn(console, "log").mockImplementation(() => {});
    errSpy = vi.spyOn(console, "error").mockImplementation(() => {});
  });
  afterEach(() => vi.restoreAllMocks());

  it("writes AGENTS.md with addendum before central fragment", async () => {
    const cfg = buildConfig({
      repo: await makeRepo(),
      templateDir: await makeTemplateDir(),
      profile: "angular",
    });
    expect(await run(cfg, { check: false })).toBe("written");
    const md = await readFile(join(cfg.repoDir, "AGENTS.md"), "utf8");
    expect(md.startsWith("<!-- Generated by agents-md-sync.")).toBe(true);
    expect(md.indexOf("Billing UI.")).toBeLessThan(md.indexOf("## Coding (angular)"));
    expect(await exists(join(cfg.repoDir, ".git"))).toBe(false);
  });

  it("scaffolds a missing PROJECT fragment and composes it in", async () => {
    const cfg = buildConfig({
      repo: await makeRepo(false),
      templateDir: await makeTemplateDir(),
      profile: "angular",
    });
    await run(cfg, { check: false });
    expect(await exists(join(cfg.repoDir, ".agents", "PROJECT.md"))).toBe(true);
    expect(await readFile(join(cfg.repoDir, "AGENTS.md"), "utf8")).toContain("## Project");
    expect(logSpy.mock.calls.some((c) => String(c[0]).includes("scaffolded"))).toBe(true);
  });

  it("--check refuses to scaffold and fails on a missing PROJECT", async () => {
    const cfg = buildConfig({
      repo: await makeRepo(false),
      templateDir: await makeTemplateDir(),
      profile: "angular",
    });
    await expect(run(cfg, { check: true })).rejects.toThrow("PROJECT.md is missing");
    expect(await exists(join(cfg.repoDir, ".agents"))).toBe(false);
  });

  it("fails on a fragment that is neither central nor local", async () => {
    const templateDir = await makeTemplateDir();
    await writeFile(
      join(templateDir, "profiles", "angular", "AGENTS.md.tmpl"),
      "<!-- include: PROJECT.md -->\n<!-- include: NOPE.md -->\n",
      "utf8",
    );
    const cfg = buildConfig({ repo: await makeRepo(), templateDir, profile: "angular" });
    await expect(run(cfg, { check: false })).rejects.toThrow("NOPE");
  });

  it("--check reports missing, out-of-date and up-to-date without writing", async () => {
    const cfg = buildConfig({
      repo: await makeRepo(),
      templateDir: await makeTemplateDir(),
      profile: "angular",
    });
    const out = join(cfg.repoDir, "AGENTS.md");

    expect(await run(cfg, { check: true })).toBe("out-of-date");
    expect(await exists(out)).toBe(false);

    await writeFile(out, "stale\n", "utf8");
    expect(await run(cfg, { check: true })).toBe("out-of-date");
    expect(await readFile(out, "utf8")).toBe("stale\n");

    await run(cfg, { check: false });
    expect(await run(cfg, { check: true })).toBe("up-to-date");
  });

  it("warns on .agents files and --skip names that match no include", async () => {
    const repo = await makeRepo();
    await writeFile(join(repo, ".agents", "CODNG.md"), "typo", "utf8");
    const cfg = buildConfig({
      repo,
      templateDir: await makeTemplateDir(),
      profile: "angular",
      skip: ["BUILD"],
    });
    await run(cfg, { check: false });
    const warnings = errSpy.mock.calls.map((c) => String(c[0]));
    expect(warnings.some((w) => w.includes(".agents/CODNG.md"))).toBe(true);
    expect(warnings.some((w) => w.includes("--skip BUILD"))).toBe(true);
  });

  it("warns when the composed file exceeds the size threshold", async () => {
    const templateDir = await makeTemplateDir();
    await writeFile(join(templateDir, "profiles", "angular", "CODING.md"), "x".repeat(13_000), "utf8");
    const cfg = buildConfig({ repo: await makeRepo(), templateDir, profile: "angular" });
    await run(cfg, { check: false });
    expect(errSpy.mock.calls.some((c) => String(c[0]).includes("threshold"))).toBe(true);
  });
});
